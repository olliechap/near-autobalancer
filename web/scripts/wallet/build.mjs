// cd web/scripts/wallet && npm install && npm run build   ->   web/vendor/wallet.js
import { build } from "esbuild";
import path from "node:path";

const here = import.meta.dirname;
await build({
  entryPoints: [path.join(here, "entry.js")],
  outfile: path.resolve(here, "../../vendor/wallet.js"),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2020",
  minify: true,
  legalComments: "eof",
  define: { "process.env.NODE_ENV": '"production"', global: "globalThis" },
  alias: { crypto: path.join(here, "crypto-stub.js") },
  inject: [path.join(here, "shims.js")],
  banner: { js: "// GENERATED by web/scripts/wallet/build.mjs from @near-wallet-selector 10.1.4 (MIT/Apache-2.0). Do not edit." },
});
console.log("web/vendor/wallet.js");
